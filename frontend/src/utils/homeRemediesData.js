// Helper function to get localized home remedies for a disease
export function getLocalizedHomeRemedies(disease, lang = 'en') {
  const d = (disease || '').toUpperCase();
  let key = 'HEALTHY';
  if (d.includes('RUST')) key = 'RUST';
  else if (d.includes('POWDERY')) key = 'POWDERY';

  const remediesList = HOME_REMEDIES_DATA[key] || HOME_REMEDIES_DATA.HEALTHY;
  const targetLang = (lang === 'te' || lang === 'hi') ? lang : 'en';

  return remediesList.map(item => {
    const loc = item[targetLang] || item.en;
    return {
      id: item.id,
      icon: item.icon,
      name: loc.name,
      ingredients: loc.ingredients,
      preparation: loc.preparation,
      application: loc.application,
      frequency: loc.frequency,
      benefit: loc.benefit
    };
  });
}
